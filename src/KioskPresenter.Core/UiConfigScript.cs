using System.Text.Json;

namespace KioskPresenter.Core;

/// <summary>
/// Builds the script the host injects before the page loads. ui/config.js swaps
/// window.KIOSK_CONFIG for window.KIOSK_HOST_CONFIG when it exists, so the design's dev
/// defaults never apply on a kiosk: dev tools are off and first-run follows the stored PIN.
/// </summary>
public static class UiConfigScript
{
    public static string Build(KioskConfig config, string? logoUrl)
    {
        var t = config.Timers;
        var payload = new
        {
            brand = new
            {
                logo = logoUrl,
                title = config.Brand.Title,
                subtitle = config.Brand.Subtitle,
                accent = IsHexColour(config.Brand.Accent) ? config.Brand.Accent : null,
            },
            motion = config.Motion,
            firstRun = config.NeedsSetup,
            timers = new
            {
                libraryIdle = t.LibraryIdle,
                playerIdle = t.PlayerIdle,
                prompt = t.Prompt,
                endAutoReturn = t.EndAutoReturn,
                openingSlow = t.OpeningSlow,
                stripHide = t.StripHide,
                cursorHide = t.CursorHide,
                inputLock = t.InputLock,
                adminHold = t.AdminHold,
            },
            dev = false,
        };
        var json = JsonSerializer.Serialize(payload, new JsonSerializerOptions { WriteIndented = true });
        return "// Generated by Kiosk Presenter from C:\\ProgramData\\KioskPresenter\\config.json.\n"
            + "window.KIOSK_HOST_CONFIG = " + json + ";\n";
    }

    public static bool IsHexColour(string? value) =>
        value is { Length: 7 } && value[0] == '#' && value[1..].All(Uri.IsHexDigit);
}
